export const ENEMY_BY_ID: Record<string, EnemyDef> = Object.fromEntries(ENEMY_DEFS.map((e) => [e.id, e]));

export const BOSS_ORDER = ['boss_lunchbox', 'boss_party', 'boss_inspector', 'boss_closing'];

export function bossForWave(wave: number): string {
  // 10, 20, 30, 40 → 순서대로. 50 이후는 순환.
  const idx = Math.floor(wave / 10) - 1;
  return BOSS_ORDER[idx % BOSS_ORDER.length];
}
